from __future__ import annotations

import argparse
from pathlib import Path


def summarize(path: Path) -> dict[str, int]:
    subjects: set[str] = set()
    predicates: set[str] = set()
    triple_count = 0
    literal_triples = 0
    resource_triples = 0
    resource_object_non_type_triples = 0
    current_subject: str | None = None
    current_predicate: str | None = None
    expect_continuation_object = False

    def parse_predicate_object(rest: str) -> bool:
        nonlocal current_predicate
        nonlocal expect_continuation_object
        nonlocal triple_count
        nonlocal literal_triples
        nonlocal resource_triples
        nonlocal resource_object_non_type_triples

        rest = rest.strip()
        if not rest:
            return False

        punctuation = rest[-1] if rest[-1] in ";,." else ""
        body = rest[:-1].strip() if punctuation else rest
        if not body:
            expect_continuation_object = punctuation == ","
            return punctuation == "."

        if expect_continuation_object:
            predicate = current_predicate
            obj = body
        else:
            parts = body.split(None, 1)
            if len(parts) < 2:
                expect_continuation_object = punctuation == ","
                return punctuation == "."
            predicate, obj = parts
            current_predicate = predicate
            predicates.add(predicate)

        if predicate is None:
            expect_continuation_object = punctuation == ","
            return punctuation == "."

        triple_count += 1
        if obj.lstrip().startswith('"'):
            literal_triples += 1
        else:
            resource_triples += 1
            if predicate != "a":
                resource_object_non_type_triples += 1

        expect_continuation_object = punctuation == ","
        return punctuation == "."

    with path.open("r", encoding="utf-8", errors="ignore") as handle:
        for raw_line in handle:
            line = raw_line.strip()
            if not line or line.startswith("@prefix") or line.startswith("#"):
                continue

            if line.startswith("<"):
                end = line.find(">")
                if end == -1:
                    continue
                current_subject = line[: end + 1]
                subjects.add(current_subject)
                current_predicate = None
                expect_continuation_object = False
                rest = line[end + 1 :].strip()
                if parse_predicate_object(rest):
                    current_subject = None
                    current_predicate = None
                    expect_continuation_object = False
            elif current_subject is not None:
                if parse_predicate_object(line):
                    current_subject = None
                    current_predicate = None
                    expect_continuation_object = False

    return {
        "unique_subjects": len(subjects),
        "triples": triple_count,
        "unique_predicates": len(predicates),
        "literal_triples": literal_triples,
        "resource_triples": resource_triples,
        "resource_object_non_type_triples": resource_object_non_type_triples,
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Summarize TTL files generated by this project without rdflib."
    )
    parser.add_argument("ttl_path", type=Path)
    args = parser.parse_args()

    stats = summarize(args.ttl_path)
    print(f"ttl_path={args.ttl_path}")
    for key, value in stats.items():
        print(f"{key}={value}")


if __name__ == "__main__":
    main()
